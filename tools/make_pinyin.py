#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
生成 MiniLaunch/src/PinyinTable.g.cs —— GB2312 全字集（一级 3755 + 二级 3008 = 6763 字）
的拼音音节表（A 方案：稠密 9bit 索引 + 位图定位 + 音节字典）。

为什么用位图 + 排名（rank）而不是逐字存储汉字：
  GB2312 的 6763 个汉字在 Unicode 里是散开的（U+4E00..U+9FA5 共 20902 个码位里只占 6763 个）。
  按 Unicode 位置直接开 20902 条 9bit 索引 = 23516 B；改用「位图(2613 B) + 6763 条索引(7609 B)」
  只要 10222 B，查表时用 popcount 求排名即可（几十行代码，O(1) 级）。

依赖：pypinyin（仅生成期需要，运行时零依赖、零 NuGet）
用法：python tools/make_pinyin.py
输出：MiniLaunch/src/PinyinTable.g.cs（UTF-8 with BOM）

数据规模（2026-11 实测）：
  汉字 6763 / 唯一音节 400 / 索引 9bit / 位图 2613 B / 索引表 7609 B ≈ 10.0 KB 数据
"""
import io
import os
import sys
import base64

from pypinyin import lazy_pinyin, Style

# Unicode 主 CJK 区：U+4E00..U+9FA5
BLOCK_LO = 0x4E00
BLOCK_HI = 0x9FA5
BLOCK_LEN = BLOCK_HI - BLOCK_LO + 1

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "MiniLaunch", "src", "PinyinTable.g.cs")


def gb2312_hanzi():
    """GB2312 全部汉字：区 0xB0..0xF7（一级 3755 + 二级 3008），按码位顺序返回。"""
    out = []
    for row in range(0xB0, 0xF8):
        for col in range(0xA1, 0xFF):
            try:
                s = bytes([row, col]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if len(s) == 1 and "\u4e00" <= s <= "\u9fff":
                out.append(s)
    return out


def pinyin_of(ch):
    r = lazy_pinyin(ch, style=Style.NORMAL, errors=lambda _x: [""])
    s = r[0].strip() if r else ""
    return s if s.isalpha() and s.isascii() else ""


def b64(data, indent="        "):
    """Base64 折行输出，便于阅读与 diff。"""
    s = base64.b64encode(data).decode("ascii")
    return "\n".join(f'{indent}"{s[i:i + 100]}" +' for i in range(0, len(s), 100))


def main():
    chars = gb2312_hanzi()
    assert len(chars) == 6763, f"GB2312 汉字数异常：{len(chars)}"

    pys = [pinyin_of(c) for c in chars]
    unknown = sum(1 for p in pys if not p)
    syllables = sorted({p for p in pys if p})
    sid = {s: i + 1 for i, s in enumerate(syllables)}  # 0 = 查不到
    bits = max(1, (len(syllables)).bit_length())
    print(f"汉字 {len(chars)} / 唯一音节 {len(syllables)} / 未识别 {unknown} / 每索引 {bits} bit")

    # ---- 位图（Unicode 位置 → 是否在表内）----
    flags = bytearray((BLOCK_LEN + 7) // 8)
    pos = []  # 每个汉字在 Unicode 区内的偏移，用于校验顺序
    for c in chars:
        off = ord(c) - BLOCK_LO
        assert 0 <= off < BLOCK_LEN, f"汉字 {c} 超出 U+4E00..U+9FA5"
        flags[off >> 3] |= 1 << (off & 7)
        pos.append(off)
    # 位图顺序（Unicode 升序）与 ids 的顺序必须一致
    order = sorted(range(len(chars)), key=lambda i: pos[i])
    ids = [sid.get(pys[i], 0) for i in order]

    # ---- 9bit 稠密打包 ----
    packed = bytearray((len(ids) * bits + 7) // 8)
    for i, v in enumerate(ids):
        bit = i * bits
        for b in range(bits):
            if v >> b & 1:
                packed[(bit + b) >> 3] |= 1 << ((bit + b) & 7)

    syl_text = " ".join(syllables)
    print(f"位图 {len(flags)} B / 索引表 {len(packed)} B / 音节表 {len(syl_text)} B "
          f"= 合计 {len(flags) + len(packed) + len(syl_text)} B")

    src = f'''// <auto-generated>
// 由 tools/make_pinyin.py 生成，勿手改（改表请改脚本再重跑）。
// 数据：GB2312 全字集（一级 3755 + 二级 3008 = {len(chars)} 字），唯一音节 {len(syllables)} 个。
// 布局：Flags 标记 U+{BLOCK_LO:04X}..U+{BLOCK_HI:04X} 内哪些码位在表内；
//       Ids 按 Unicode 升序、每字 {bits} bit 存字号（0 = 无拼音）；
//       Syllables 为空格分隔的音节表（字号 = 下标 + 1）。
// 体积：位图 {len(flags)} B + 索引 {len(packed)} B + 音节表 {len(syl_text)} B。
// </auto-generated>

namespace MiniLaunch;

public static partial class PinyinTable
{{
    public const int BlockLo = 0x{BLOCK_LO:04X};
    public const int BlockLen = {BLOCK_LEN};
    public const int BitsPerIndex = {bits};

    /// <summary>音节表，空格分隔；下标从 0 开始，字号 = 下标 + 1（0 表示无拼音）。</summary>
    public const string Syllables = "{syl_text}";

    /// <summary>位图：bit(码位 - BlockLo) = 1 表示该码位在拼音表内。</summary>
    public static readonly byte[] Flags = System.Convert.FromBase64String(
{b64(bytes(flags))}
        "");

    /// <summary>稠密索引：按 Unicode 升序，每字 {bits} bit。</summary>
    public static readonly byte[] Ids = System.Convert.FromBase64String(
{b64(bytes(packed))}
        "");
}}
'''
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    io.open(OUT, "w", encoding="utf-8-sig", newline="\n").write(src)
    print(f"已生成 {OUT}（{os.path.getsize(OUT)} B）")


if __name__ == "__main__":
    sys.exit(main())
